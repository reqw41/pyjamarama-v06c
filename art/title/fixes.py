# Правки раскраски заставки (попиксельно). apply(px) -> px; px[y][x] = код цвета ZX 0..7 (0 контур, 1 синий, 2 красный, 3 розовый, 4 зелёный, 5 голубой, 6 золотой, 7 кремовый).
def box(px,x0,y0,x1,y1,m):
    """в прямоугольнике [x0,x1) x [y0,y1) заменить цвета по словарю m"""
    for y in range(y0,y1):
        for x in range(x0,x1):
            v=px[y][x]
            if v in m: px[y][x]=m[v]
def cell(px,cx,cy,m): box(px,cx*8,cy*8,cx*8+8,cy*8+8,m)
def apply(px):
    # Уолли: волосы — золотые (убрать белый квадрат атрибута слева), шея — кремовая, пижама — кремовая с синими полосками
    cell(px,16,11,{7:6})
    for cx in (17,18,19): cell(px,cx,14,{6:7})
    box(px,112,126,168,151,{2:1})
    cell(px,17,15,{6:7}); box(px,144,118,156,128,{2:1})
    # голова: подбородок и рот — кожа (кремовая), справа от овала лица — волосы (золотые)
    box(px,128,104,160,112,{6:7})
    box(px,155,95,160,104,{7:6})
    box(px,142,118,152,128,{6:7})
    # левая прядь волос — плоский золотой квадрат атрибута: добавить красную штриховку, как у остальных волос
    for y in range(86,104):
        for x in range(120,136):
            if px[y][x]==6 and (x*3+y*5)%7==0: px[y][x]=2
    # плоские золотые квадраты атрибутов (кроме полос обоев слева) — «ткань» с красной штриховкой, как у волос: без резких блоков
    for cy in range(24):
        for cx in range(32):
            if cx<8: continue
            vals=[px[y][x] for y in range(cy*8,cy*8+8) for x in range(cx*8,cx*8+8)]
            nz=[v for v in vals if v!=0]
            if len(nz)>=40 and sum(1 for v in nz if v==6)>=0.9*len(nz):
                for y in range(cy*8,cy*8+8):
                    for x in range(cx*8,cx*8+8):
                        if px[y][x]==6 and (x*3+y*5)%7==0: px[y][x]=2
                        elif px[y][x]==6 and (x+y)%4==0 and cx>=22: px[y][x]=7
    return px
